#!/usr/bin/env node
/**
 * Build-time diagnostic generator.
 *
 * Loads every authored lesson via Vite SSR, runs the Strada Compiler API
 * (typescript-strada@6.0.3) through the virtual host, and writes
 * `src/curriculum/generated/diagnostics.ts`.
 *
 * Usage: node scripts/generate-diagnostics.mjs [--check]
 *   --check  exit non-zero if the file is missing or would change; write nothing
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { createServer } from "vite";
import vue from "@vitejs/plugin-vue";

import {
  loadStradaLibs,
  STRADA_VERSION,
  stradaTs,
} from "./load-strada-libs.mjs";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const outPath = resolve(
  repoRoot,
  "src/curriculum/generated/diagnostics.ts",
);
const checkOnly = process.argv.includes("--check");

const server = await createServer({
  configFile: false,
  root: repoRoot,
  plugins: [vue()],
  resolve: {
    alias: {
      "@": resolve(repoRoot, "src"),
    },
  },
  // Avoid pulling the full app CSS / public pipeline for a Node script.
  server: { middlewareMode: true },
  appType: "custom",
});

try {
  const { allLessons, isPlaceholder } = await server.ssrLoadModule(
    "/src/curriculum/index.ts",
  );
  const { createTypecheckSession, BASELINE_LIB } = await server.ssrLoadModule(
    "/src/typecheck/host.ts",
  );

  const libs = loadStradaLibs([BASELINE_LIB, "dom", "dom.iterable"]);
  const session = createTypecheckSession({ ts: stradaTs, libs });

  /** @type {Record<string, { pane: unknown; starter?: unknown; solution?: unknown }>} */
  const byLesson = {};

  for (const lesson of allLessons) {
    if (isPlaceholder(lesson.ts)) continue;

    const pane = session.check(lesson.ts.code).diagnostics;
    const entry = { pane };

    if (lesson.exercise) {
      entry.starter = session.check(lesson.exercise.starter).diagnostics;
      if (lesson.exercise.solution) {
        entry.solution = session.check(lesson.exercise.solution).diagnostics;
      }
    }

    byLesson[lesson.id] = entry;
  }

  session.dispose();

  const banner = `/**
 * AUTO-GENERATED by scripts/generate-diagnostics.mjs — do not edit.
 * Strada (typescript-strada) version: ${STRADA_VERSION}
 * Regenerated by predev / prebuild / generate:diagnostics.
 */
`;

  const raw = `${banner}
import type { TsDiagnostic } from "@/typecheck/types";

export interface LessonDiagnostics {
  pane: readonly TsDiagnostic[];
  starter?: readonly TsDiagnostic[];
  solution?: readonly TsDiagnostic[];
}

export const STRADA_COMPILER_VERSION = ${JSON.stringify(STRADA_VERSION)} as const;

export const LESSON_DIAGNOSTICS: Readonly<Record<string, LessonDiagnostics>> =
  ${JSON.stringify(byLesson, null, 2)} as const;
`;

  // Match `pnpm format` so --check stays green after Prettier runs on src/.
  const prettierOpts = await prettier.resolveConfig(outPath);
  const body = await prettier.format(raw, {
    ...prettierOpts,
    filepath: outPath,
  });

  const nextHash = createHash("sha256").update(body).digest("hex");

  if (checkOnly) {
    let current = "";
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      console.error(
        `generate-diagnostics --check: missing ${outPath}. Run pnpm generate:diagnostics.`,
      );
      process.exit(1);
    }
    const currentHash = createHash("sha256").update(current).digest("hex");
    if (currentHash !== nextHash) {
      console.error(
        "generate-diagnostics --check: src/curriculum/generated/diagnostics.ts is stale. Run pnpm generate:diagnostics.",
      );
      process.exit(1);
    }
    console.warn(
      `generate-diagnostics --check: ok (${Object.keys(byLesson).length} lessons, Strada ${STRADA_VERSION})`,
    );
    process.exit(0);
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, body);
  console.warn(
    `generate-diagnostics: wrote ${Object.keys(byLesson).length} lessons → ${outPath} (Strada ${STRADA_VERSION})`,
  );
} finally {
  await server.close();
}
